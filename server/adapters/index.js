// M08 Unified Subject Adapter Registry
// Allows adding new deterministic discipline adapters without modifying M02/M05 core state machine.
import { chemistryAdapter } from './chemistry.js'
import { mathAdapter } from './math.js'

function genericAdapter(subjectId) {
  return {
    subjectId,
    ruleVersion: 'generic-semantic-v1.0',
    supportsDeterministicCheck: false,
    evaluateExploration: ({ config }) => ({
      verdict: 'observed',
      evidenceSource: 'self_report',
      ruleVersion: 'generic-semantic-v1.0',
      skillId: `${subjectId}.general`,
      misconception: null,
      fact: `提交了可视化组件（${config?.component || 'explorer'}）的探索操作（通用学科未配置专用校验器，需结合语义核验）。`,
    }),
    evaluateAnswer: ({ question, value, answerText }) => {
      if (question?.type === 'choice' || question?.type === 'multi_choice') {
        const correct = question.type === 'multi_choice'
          ? Array.isArray(value) && Array.isArray(question.answer) && value.length === question.answer.length && [...value].sort().every((v, i) => v === [...question.answer].sort()[i])
          : value === question.answer
        const isUnknown = Boolean(question.isUnknown)
        // Choice options generated by LLM on un-adapted subjects still mark objective choice verdict,
        // while open-ended answers explicitly mark llm_semantic / unverified.
        return {
          verdict: isUnknown ? 'uncertain' : correct ? 'correct' : 'incorrect',
          evidenceSource: 'llm_semantic',
          ruleVersion: 'generic-semantic-v1.0',
          skillId: `${subjectId}.general`,
          misconception: null,
          fact: `在通用学科作答「${answerText}」（该学科暂未配置专用确定性规则校验器，结论待进一步核验）。`,
        }
      }
      if (question?.type === 'number') {
        const correct = Math.abs(Number(value) - Number(question.answer)) <= (question.tolerance ?? 0)
        return {
          verdict: correct ? 'correct' : 'incorrect',
          evidenceSource: 'llm_semantic',
          ruleVersion: 'generic-semantic-v1.0',
          skillId: `${subjectId}.general`,
          misconception: null,
          fact: `数值作答 ${value}（未配备专用学科规则校验器，按题目参考值核对${correct ? '一致' : '不一致'}）。`,
        }
      }
      return {
        verdict: 'observed',
        evidenceSource: 'llm_semantic',
        ruleVersion: 'generic-semantic-v1.0',
        skillId: `${subjectId}.general`,
        misconception: null,
        fact: `开放作答「${String(answerText || '').slice(0, 200)}」（未配备确定性校验器，需结合语义评估确认）。`,
      }
    },
  }
}

const adapters = new Map([
  ['chemistry', chemistryAdapter],
  ['math', mathAdapter],
])

export function getAdapter(subjectId) {
  return adapters.get(subjectId) || genericAdapter(subjectId || 'general')
}

export function listAdapters() {
  return Array.from(adapters.values()).map((a) => ({
    subjectId: a.subjectId,
    ruleVersion: a.ruleVersion,
    supportsDeterministicCheck: a.supportsDeterministicCheck,
  }))
}
